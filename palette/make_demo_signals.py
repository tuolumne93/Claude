#!/usr/bin/env python3
"""Generate SYNTHETIC demo signals so you can try trendcast.py.

The colour stories below are invented to show each trend stage (emerging,
rising, peak, declining). They are not a real forecast.
"""

import csv
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from tablekit.colorsci import hex_to_lab, lab_to_hex  # noqa: E402

# name: (hex, leading share start->end, market share start->end)
STORIES = {
    "butter yellow":   ("#F2E2A0", (0.03, 0.14), (0.01, 0.04)),   # emerging
    "cherry red":      ("#B3222F", (0.02, 0.10), (0.01, 0.02)),   # emerging
    "chocolate brown": ("#5E3B2E", (0.03, 0.11), (0.01, 0.03)),   # emerging
    "lilac":           ("#C6B4DD", (0.04, 0.09), (0.03, 0.07)),   # rising
    "sage":            ("#A6B79A", (0.13, 0.04), (0.16, 0.12)),   # declining
    "mint":            ("#A5DBC6", (0.08, 0.03), (0.10, 0.05)),   # declining
    "terracotta":      ("#C66F4F", (0.08, 0.08), (0.11, 0.11)),   # peak
    "dusty blue":      ("#8EA7BF", (0.08, 0.09), (0.09, 0.09)),   # stable
    "oatmeal":         ("#E5DBCA", (0.14, 0.15), (0.16, 0.16)),   # neutral core
    "sky blue":        ("#9FCBEA", (0.04, 0.07), (0.04, 0.06)),
}
SOURCES = {"leading": ["forecast_agency", "adult_fashion", "interiors", "social"],
           "bridge": ["kids_fashion", "nursery_interiors"],
           "market": ["competitor_launch", "retail_bestseller"]}


def main(out="palette/sample_signals.csv", seed=7):
    rnd = random.Random(seed)
    quarters = [(2024 + i // 4, i % 4) for i in range(11)]  # 2024-Q1 .. 2026-Q3
    rows = []
    for qi, (year, q) in enumerate(quarters):
        t = qi / (len(quarters) - 1)
        for role, types in SOURCES.items():
            shares = {}
            for name, (hx, lead, mkt) in STORIES.items():
                ls = lead[0] + (lead[1] - lead[0]) * t
                ms = mkt[0] + (mkt[1] - mkt[0]) * t
                shares[name] = {"leading": ls, "market": ms, "bridge": 0.5 * (ls + ms)}[role]
            total = sum(shares.values())
            for name, s in shares.items():
                n = round(60 * s / total + rnd.uniform(-0.6, 0.6))
                L, a, b = hex_to_lab(STORIES[name][0])
                for _ in range(max(0, n)):
                    jit = lab_to_hex((L + rnd.gauss(0, 2.5), a + rnd.gauss(0, 2.5), b + rnd.gauss(0, 2.5)))
                    st = rnd.choice(types)
                    rows.append([f"{year}-{q * 3 + rnd.randint(1, 3):02d}-{rnd.randint(1, 28):02d}", jit, st,
                                 f"demo {st.replace('_', ' ')}", 1, ""])
    rows.sort()
    with open(out, "w", newline="") as fh:
        fh.write("# SYNTHETIC DEMO DATA generated by make_demo_signals.py - invented colour stories, not a real forecast.\n")
        w = csv.writer(fh)
        w.writerow(["date", "hex", "source_type", "source_name", "weight", "notes"])
        w.writerows(rows)
    print(f"wrote {len(rows)} signals to {out}")


if __name__ == "__main__":
    main(*sys.argv[1:2])
